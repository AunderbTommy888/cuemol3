/** The colours (`#rrggbb`) of a ColorBrewer palette, or null for a name that is not one. */
export function colorBrewerPalette(name: string): string[] | null {
  const packed = PALETTES[name.toLowerCase()]
  if (packed === undefined) return null
  const out: string[] = []
  for (let i = 0; i < packed.length; i += 6) out.push(`#${packed.slice(i, i + 6)}`)
  return out
}
